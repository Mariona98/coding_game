package com.example;

public class Level_1_Data {

    public int heroX;
    public int heroY;

    public int keyX;
    public int keyY;

    public int goalX;
    public int goalY;

    public Level_1_Data(int heroX, int heroY, int keyX, int keyY, int goalX, int goalY) {

        this.heroX = heroX;
        this.heroY = heroY;

        this.keyX = keyX;
        this.keyY = keyY;

        this.goalX = goalX;
        this.goalY = goalY;
    }
}